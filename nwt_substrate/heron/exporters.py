def submit_to_heron(qc, backend_name="{backend}", shots={shots}):
    """Transpile + submit to IBM Heron, return a Sampler result."""
    from qiskit import transpile
    from qiskit_ibm_runtime import QiskitRuntimeService, SamplerV2 as Sampler

    token = os.environ.get("QISKIT_IBM_TOKEN")
    if not token:
        raise RuntimeError(
            "QISKIT_IBM_TOKEN not set.  Get a token at "
            "https://quantum.ibm.com/  and `export QISKIT_IBM_TOKEN=...`"
        )

    service = QiskitRuntimeService(token=token, channel="ibm_quantum")
    backend = service.backend(backend_name)
    print(f"Submitting to {{backend.name}} ({{backend.num_qubits}} qubits)...")

    qc_compiled = transpile(qc, backend=backend, optimization_level=3)
    sampler = Sampler(backend)
    job = sampler.run([qc_compiled], shots=shots)
    print(f"Job ID: {{job.job_id()}}")
    print("Waiting for result...")
    return job.result()


