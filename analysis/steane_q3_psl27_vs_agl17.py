# ---------------------------------------------------------------------------
# Permutation utilities on 7 points
# ---------------------------------------------------------------------------

def perm_order(perm: tuple[int, ...]) -> int:
    """Order of a permutation given as a tuple where perm[i] = image of i."""
    n = len(perm)
    visited = [False] * n
    order = 1
    for i in range(n):
        if visited[i]:
            continue
        cycle_len = 0
        j = i
        while not visited[j]:
            visited[j] = True
            j = perm[j]
            cycle_len += 1
        order = order * cycle_len // gcd(order, cycle_len)
    return order


def perm_compose(p: tuple, q: tuple) -> tuple:
    """Compose two permutations: (p∘q)[i] = p[q[i]]."""
    return tuple(p[q[i]] for i in range(len(p)))


def perm_identity(n: int) -> tuple:
    return tuple(range(n))


def perm_inverse(p: tuple) -> tuple:
    inv = [0] * len(p)
    for i, j in enumerate(p):
        inv[j] = i
    return tuple(inv)


def generate_subgroup(generators: list[tuple], n: int) -> set[tuple]:
    """BFS enumeration of the subgroup of S_n generated by the given perms."""
    elements = {perm_identity(n)}
    frontier = {perm_identity(n)}
    while frontier:
        new_frontier = set()
        for g in frontier:
            for h in generators:
                gh = perm_compose(g, h)
                if gh not in elements:
                    elements.add(gh)
                    new_frontier.add(gh)
        frontier = new_frontier
    return elements


# ---------------------------------------------------------------------------
# AGL(1, 7) construction: x ↦ ax + b
# ---------------------------------------------------------------------------

def affine_perm(a: int, b: int, q: int = 7) -> tuple:
    return tuple((a * x + b) % q for x in range(q))


def agl_1_7() -> set[tuple]:
    """All 42 elements of AGL(1, 7) as permutations of F_7."""
    return {affine_perm(a, b) for a in range(1, 7) for b in range(7)}


# ---------------------------------------------------------------------------
# GL(3, 2) construction: invertible 3×3 binary matrices on F_2^3
# ---------------------------------------------------------------------------

def matrix_invertible_F2(M: np.ndarray) -> bool:
    # Determinant in F_2 by Gaussian elimination
    A = M.copy() % 2
    n = A.shape[0]
    for col in range(n):
        pivot = -1
        for row in range(col, n):
            if A[row, col] == 1:
                pivot = row
                break
        if pivot < 0:
            return False
        if pivot != col:
            A[[col, pivot]] = A[[pivot, col]]
        for row in range(n):
            if row != col and A[row, col] == 1:
                A[row] = (A[row] + A[col]) % 2
    return True


def gl_3_2_matrices() -> list[np.ndarray]:
    """All 168 elements of GL(3, 2)."""
    elements = []
    for bits in product([0, 1], repeat=9):
        M = np.array(bits, dtype=int).reshape(3, 3)
        if matrix_invertible_F2(M):
            elements.append(M)
    return elements


# Standard NWT VERTEX_TO_FANO map: K_7 vertex → F_2^3 \ {0}
VERTEX_TO_FANO = {
    0: (1, 1, 1), 1: (1, 0, 0), 2: (0, 1, 0), 3: (0, 0, 1),
    4: (0, 1, 1), 5: (1, 0, 1), 6: (1, 1, 0),
}
FANO_TO_VERTEX = {v: k for k, v in VERTEX_TO_FANO.items()}


def gl_perm(M: np.ndarray) -> tuple:
    """Action of M ∈ GL(3,2) on K_7 vertices via VERTEX_TO_FANO."""
    perm = [0] * 7
    for v in range(7):
        x = np.array(VERTEX_TO_FANO[v]) % 2
        y = tuple((M @ x) % 2)
        perm[v] = FANO_TO_VERTEX[y]
    return tuple(perm)


def psl_2_7() -> set[tuple]:
    """All 168 elements of GL(3, 2) ≅ PSL(2, 7) as permutations of K_7 vertices."""
    return {gl_perm(M) for M in gl_3_2_matrices()}


