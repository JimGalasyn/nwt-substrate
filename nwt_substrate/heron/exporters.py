def export_experiment_script(n: int,
                              output_path: str | Path,
                              backend: str = "ibm_marrakesh",
                              shots: int = 10000) -> Path:
    """
    Generate a self-contained Python script for the given experiment.

    The script has no nwt_substrate dependency at runtime — anyone with
    `pip install qiskit qiskit-ibm-runtime` and an IBM Quantum token can
    run it directly.
    """
    exp = _get_experiment(n)
    builder_fn, builder_args = _BUILDERS[n]

    builder_source = inspect.getsource(builder_fn)
    # Strip the type-quoted return annotation since this is now standalone
    builder_source = builder_source.replace(
        '-> "QuantumCircuit":', '-> "QuantumCircuit":\n'
        '    from qiskit import QuantumCircuit, ClassicalRegister'
    )
    # Replace the HAS_QISKIT guard (not relevant in the standalone script)
    builder_source = builder_source.replace(
        '    if not HAS_QISKIT:\n        raise RuntimeError("qiskit not installed")\n',
        '',
    ).replace(
        '    if not HAS_QISKIT:\n        raise RuntimeError("qiskit not installed; pip install qiskit")\n',
        '',
    )

    description_wrapped = textwrap.fill(exp.description, width=72,
                                        subsequent_indent="")

    analysis_doc, analysis_extra = _ANALYSIS_STUBS[n]
    analysis_doc = textwrap.fill(analysis_doc, width=68,
                                  subsequent_indent="    ")

    output_path = Path(output_path)
    underline = "=" * (len(exp.name) + 4)

    script = SCRIPT_TEMPLATE.format(
        n=n,
        name=exp.name,
        underline=underline,
        description_wrapped=description_wrapped,
        status=exp.status,
        backend=exp.backend or backend,
        paper=exp.paper_section or "TBD",
        shots=shots,
        filename=output_path.name,
        builder_source=builder_source,
        builder_name=builder_fn.__name__,
        builder_args=builder_args,
        analysis_doc=analysis_doc,
        analysis_extra=analysis_extra,
    )
    output_path.write_text(script)
    return output_path


def export_all_experiments(output_dir: str | Path,
                            backend: str = "ibm_marrakesh",
                            shots: int = 10000) -> list[Path]:
    """Export all 9 experiments as standalone scripts in `output_dir`."""
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    paths = []
    for exp in EXPERIMENTS:
        slug = exp.name.lower().replace(" ", "_").replace("(", "").replace(")", "")
        slug = slug.replace(",", "").replace("/", "_").replace(":", "")
        slug = slug.replace("-", "_").replace("=", "_eq_")[:60]
        filename = f"exp{exp.number:02d}_{slug}.py"
        path = export_experiment_script(
            exp.number, output_dir / filename,
            backend=backend, shots=shots,
        )
        paths.append(path)
    return paths
